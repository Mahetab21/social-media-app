import * as z from 'zod';
import { generalRules } from '../../utils/generalRules';
import { OnModelEnum } from '../../DB/model/comment.model';
const params = z.object({ postId: generalRules.id, commentId: generalRules.id });
const tags = z.array(generalRules.id).max(20).refine(ids => new Set(ids).size === ids.length, 'Duplicate tags').optional();
const body = z.strictObject({ content: z.string().trim().min(3).max(5000).optional(), attachments: z.array(generalRules.file).max(2).optional(), tags, onModel: z.enum(OnModelEnum).optional() });
export const createCommentSchema = { params: params.extend({ commentId: generalRules.id.optional() }), body: body.extend({ onModel: z.enum(OnModelEnum) }).refine(x => !!x.content || !!x.attachments?.length, 'Content or an attachment is required') };
export const updateCommentSchema = { params, body: body.refine(x => x.content !== undefined || x.tags !== undefined || !!x.attachments?.length, 'Provide an update') };
export const freezeCommentSchema = { params };
export const hardDeleteCommentSchema = { params };
export const getCommentsByIdSchema = { params: z.object({ postId: generalRules.id }) };
export const getCommentWithReplySchema = { params };
