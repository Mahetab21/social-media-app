import { Router } from 'express';
import CS from './comment.service';
import { Authentication } from '../../middleware/Authentication';
import { Validation } from '../../middleware/validation';
import * as V from './comment.validation';
import { multerCloud } from '../../middleware/multer.cloud';
const router = Router({ mergeParams: true });
router.use(Authentication());
router.post(['/', '/:commentId'], multerCloud({}).array('attachments', 2), Validation(V.createCommentSchema), CS.createComment);
router.get('/', Validation(V.getCommentsByIdSchema), CS.getCommentsById);
router.get('/:commentId', Validation(V.getCommentWithReplySchema), CS.getCommentWithReply);
router.patch('/freeze/:commentId', Validation(V.freezeCommentSchema), CS.freezeComment);
router.patch('/:commentId', multerCloud({}).array('attachments', 2), Validation(V.updateCommentSchema), CS.updateComment);
router.delete('/:commentId', Validation(V.hardDeleteCommentSchema), CS.hardDeleteComment);
export default router;
